type ActorKey = keyof typeof recordedActors;

function entry(
  actor: ActorKey | "unknown",
  organizationId: string,
  organizationName: string,
  values: {
    id: string;
    eventName: string;
    actionType: AuditLog["actionType"];
    module: AuditLog["module"];
    entityType: string;
    entityId: string;
    entityName: string;
    description: string;
    status: AuditLog["status"];
    timestamp: string;
    ipAddress: string;
    userAgent?: string;
    changes?: AuditChange[];
  },
): AuditLog {
  const person = actor === "unknown" ? undefined : recordedActors[actor];

  return {
    id: values.id,
    eventName: values.eventName,
    actionType: values.actionType,
    module: values.module,
    actorId: person?.id ?? "sample-removed-user",
    actorName: person?.name ?? "",
    actorEmail: person?.email ?? "",
    actorRole: person?.role ?? "",
    organizationId,
    organizationName,
    entityType: values.entityType,
    entityId: values.entityId,
    entityName: values.entityName,
    description: values.description,
    status: values.status,
    timestamp: values.timestamp,
    ipAddress: values.ipAddress,
    userAgent: values.userAgent ?? desktop,
    changes: values.changes ?? [],
  };
}

